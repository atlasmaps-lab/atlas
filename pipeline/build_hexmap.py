"""
Atlas 1.7: constituency hex maps -> data/hex_constituencies.js   (python3 pipeline/build_hexmap.py; standard library only)

Open Innovations HexJSON (MIT licence): uk-constituencies-2023.hexjson (the 2024 seats) and constituencies.hexjson (the
2010-2024 seats). One hexagon per seat, laid out by Open Innovations so neighbours stay roughly neighbours. Atlas draws them
as ordinary polygons over the UK's bounding box (regular hexagons on the Web Mercator map), with the same codes as the real
boundaries, so colours, cards and clicks work unchanged.
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RAW = os.path.join(HERE, "sources", "raw")
BOX = (-7.9, 50.0, 1.9, 60.6)   # lon/lat box the hex map is fitted into (keeps it over the UK)


def merc(lon, lat):
    return math.radians(lon), math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


def unmerc(x, y):
    return math.degrees(x), math.degrees(2 * math.atan(math.exp(y)) - math.pi / 2)


def layout(hexjson, prefix):
    j = json.load(open(os.path.join(RAW, hexjson), encoding="utf-8"))
    assert j["layout"] == "odd-r", j["layout"]
    pts = {}
    for code, h in j["hexes"].items():   # odd-r: pointy-topped, odd rows shifted half a hex right; r grows northwards
        q, r = h["q"], h["r"]
        pts[code] = (math.sqrt(3) * (q + 0.5 * (r & 1)), 1.5 * r, h["n"])
    xs = [p[0] for p in pts.values()]; ys = [p[1] for p in pts.values()]
    (x0, y0), (x1, y1) = merc(BOX[0], BOX[1]), merc(BOX[2], BOX[3])
    pad = 1.2
    s = min((x1 - x0) / (max(xs) - min(xs) + 2 * pad), (y1 - y0) / (max(ys) - min(ys) + 2 * pad))
    ox = x0 + ((x1 - x0) - s * (max(xs) - min(xs))) / 2 - s * min(xs)
    oy = y0 + ((y1 - y0) - s * (max(ys) - min(ys))) / 2 - s * min(ys)
    feats = []
    for code, (x, y, name) in pts.items():
        ring = []
        for k in range(7):
            a = math.radians(60 * k + 30)
            lon, lat = unmerc(ox + s * (x + 0.96 * math.cos(a)), oy + s * (y + 0.96 * math.sin(a)))
            ring.append([round(lon, 5), round(lat, 5)])
        c = unmerc(ox + s * x, oy + s * y)
        feats.append({"type": "Feature", "properties": {"code": prefix + code, "name": name, "level": "constituency", "pt": [round(c[0], 5), round(c[1], 5)]},
                      "geometry": {"type": "Polygon", "coordinates": [ring]}})
    return {"type": "FeatureCollection", "features": feats}


def main():
    out = {"2024": layout("hex_uk-constituencies-2023.hexjson", ""), "2010": layout("hex_constituencies.hexjson", "P10-"),
           "source": "Open Innovations HexJSON (github.com/odileeds/hexmaps, MIT licence): uk-constituencies-2023 and constituencies"}
    path = os.path.join(ROOT, "data", "hex_constituencies.js")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// Generated by pipeline/build_hexmap.py. Do not edit by hand.\nwindow.ATLAS_HEX = ")
        json.dump(out, fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"hex maps: 2024 {len(out['2024']['features'])} seats, 2010 {len(out['2010']['features'])} seats, {os.path.getsize(path) / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
