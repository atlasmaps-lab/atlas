"""
Atlas 1.7: local government figures -> data/local.js   (python3 pipeline/build_local.py; standard library only)

Packs the tidy files written by clean_counciltax.py (and, when present, clean_representation.py and clean_councils.py):
window.ATLAS_LOCAL = {
  bandd: { council code: { first financial year: [Band D £ for that year, the next, ...] } }   (null where missing)
  cpih:  { first year: [April CPIH, ...] }    ONS L522, 2015 = 100
  ... more blocks as their sources are added
  sources: { ... }
}
"""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "sources")


def series(rows, key, val):
    by = {}
    for r in rows:
        by.setdefault(r[key], {})[int(r["fy"])] = float(r[val])
    out = {}
    for k, d in by.items():
        y0, y1 = min(d), max(d)
        out[k] = {str(y0): [d.get(y) for y in range(y0, y1 + 1)]}
    return out


def main():
    out = {"sources": {}}
    p = os.path.join(SRC, "council_tax_band_d.csv")
    if os.path.exists(p):
        out["bandd"] = series(list(csv.DictReader(open(p, encoding="utf-8"))), "code", "band_d")
        out["sources"]["bandd"] = ("England: MHCLG Band D council tax live table (area council tax, including parish precepts), 1993-94 onwards; "
                                   "Scotland: Scottish Government Council Tax by band, 2014-15 onwards; Wales: StatsWales, total Band D for the billing authority area, 1993-94 onwards")
    p = os.path.join(SRC, "cpih_april.csv")
    if os.path.exists(p):
        rows = list(csv.DictReader(open(p, encoding="utf-8")))
        y0 = min(int(r["fy"]) for r in rows)
        out["cpih"] = {str(y0): [float(r["cpih_april"]) for r in sorted(rows, key=lambda r: int(r["fy"]))]}
        out["sources"]["cpih"] = "ONS CPIH index 00: all items, 2015 = 100 (series L522), April of each financial year"
    path = os.path.join(ROOT, "data", "local.js")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// Generated by pipeline/build_local.py. Do not edit by hand.\nwindow.ATLAS_LOCAL = ")
        json.dump(out, fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"local.js: {', '.join(k for k in out if k != 'sources')}; {os.path.getsize(path) / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
