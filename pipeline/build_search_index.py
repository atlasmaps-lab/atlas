"""
Atlas 0.13: the search box's index of named things whose shapes load only when needed -> data/search_index.js
  rivers   the main rivers, canals and tidal reaches (data/rivers/main.js), with their length and bounding box
  parks    National Parks and Ramsar sites (data/envzones/conservation.js)
  coast    shoreline management plan stretches (data/envzones/coast.js)
Run after build_rivers.py / build_envzones.py:   python3 pipeline/build_search_index.py
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def payload(path):
    s = open(os.path.join(ROOT, path), encoding="utf-8").read()
    i = s.index("(", s.index("_LOADED(")); j = s.index(",", i)
    return json.loads(s[j + 1:s.rindex(")")].strip())


def bbox_rings(polys, scale):
    xs, ys = [], []
    for poly in polys:
        for flat in poly:
            x = y = 0
            for k in range(0, len(flat), 2):
                x += flat[k]; y += flat[k + 1]; xs.append(x / scale); ys.append(y / scale)
    return [round(min(xs), 4), round(min(ys), 4), round(max(xs), 4), round(max(ys), 4)] if xs else None


def merge(a, b):
    return b if not a else [min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3])]


def main():
    out = {"rivers": [], "parks": [], "coast": []}
    R = payload("data/rivers/main.js")
    FORM = {"t": "Tidal river", "c": "Canal", "r": "River", "l": "Lake"}
    for props, lines in R["lines"]:
        if not props.get("n"):
            continue
        b = None; km = 0.0
        for flat in lines:
            x = y = 0; prev = None
            for k in range(0, len(flat), 2):
                x += flat[k]; y += flat[k + 1]; p = (x / 1e5, y / 1e5)
                b = merge(b, [p[0], p[1], p[0], p[1]])
                if prev:
                    km += math.hypot((p[0] - prev[0]) * 111.32 * math.cos(math.radians(p[1])), (p[1] - prev[1]) * 110.57)
                prev = p
        out["rivers"].append([props["n"], FORM.get(props.get("f"), "River"), round(km), [round(v, 4) for v in b]])
    # pieces of one river come separately: join same-named pieces that touch (several River Avons stay apart)
    near = lambda a, b: a[0] - 0.12 <= b[2] and b[0] - 0.12 <= a[2] and a[1] - 0.12 <= b[3] and b[1] - 0.12 <= a[3]
    joined = []
    for r in sorted(out["rivers"], key=lambda r: -r[2]):
        for j in joined:
            if j[0] == r[0] and near(j[3], r[3]):
                j[2] += r[2]; j[3] = merge(j[3], r[3]); break
        else:
            joined.append([r[0], r[1], r[2], list(r[3])])
    changed = True
    while changed:   # pieces joined later may now touch each other
        changed = False
        for i in range(len(joined)):
            for k in range(i + 1, len(joined)):
                if joined[i][0] == joined[k][0] and near(joined[i][3], joined[k][3]):
                    joined[i][2] += joined[k][2]; joined[i][3] = merge(joined[i][3], joined[k][3]); del joined[k]; changed = True; break
            if changed:
                break
    out["rivers"] = [[n, f, km, [round(v, 4) for v in b]] for n, f, km, b in sorted(joined, key=lambda r: -r[2]) if km >= 2]
    C = payload("data/envzones/conservation.js")
    for props, polys in C["features"]:
        b = bbox_rings(polys, 1e4)
        if b and props.get("n"):
            out["parks"].append([props["n"], "National Park" if props.get("k") == "np" else "Ramsar site", b])
    K = payload("data/envzones/coast.js"); smp = {}
    for props, polys in K["features"]:
        b = bbox_rings(polys, 1e4)
        if b and props.get("smp"):
            smp[props["smp"]] = merge(smp.get(props["smp"]), b)
    out["coast"] = [[n, "Coastal stretch", [round(v, 4) for v in b]] for n, b in sorted(smp.items())]
    with open(os.path.join(ROOT, "data", "search_index.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by pipeline/build_search_index.py: named rivers (OS Open Rivers), National Parks and Ramsar sites, shoreline stretches. OGL v3.0. */\nwindow.ATLAS_SEARCH_INDEX = ")
        json.dump(out, fh, ensure_ascii=False, separators=(",", ":")); fh.write(";\n")
    print({k: len(v) for k, v in out.items()})


if __name__ == "__main__":
    main()
