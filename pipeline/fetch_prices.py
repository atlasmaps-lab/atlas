"""
Atlas 1.8: end-of-day share prices for the FTSE 100 -> data/prices.js   (run by .github/workflows/prices.yml)

Switched off until a provider whose licence allows public display is chosen (pipeline/sources/prices_licence.md).
Needs two environment variables (in the Action, from repository secrets/variables):
  PRICES_PROVIDER   the adapter to use (none is written yet)
  PRICES_API_KEY    the provider's key; never put it in the page or the repository
Writes window.ATLAS_PRICES = { asof, provider, licence, delayed: true, prices: { "III.L": [[date, close], ...] } }.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "data", "prices.js")
ADAPTERS = {}   # name -> function(symbols, key) -> {symbol: [[date, close], ...]}; add one once a provider's terms allow public display


def main():
    provider, key = os.environ.get("PRICES_PROVIDER", ""), os.environ.get("PRICES_API_KEY", "")
    if provider not in ADAPTERS or not key:
        print("No licensed price provider is configured (see pipeline/sources/prices_licence.md); data/prices.js is left as it is.")
        return 0
    s = open(os.path.join(os.path.dirname(HERE), "data", "markets.js"), encoding="utf-8").read()
    syms = [c["sym"] for c in json.loads(s[s.index("=") + 1:].strip().rstrip(";"))["companies"] if c.get("sym")]
    prices = ADAPTERS[provider](syms, key)
    asof = max((p[-1][0] for p in prices.values() if p), default="")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by pipeline/fetch_prices.py. Do not edit by hand.\nwindow.ATLAS_PRICES = " + json.dumps({"asof": asof, "provider": provider, "delayed": True, "prices": prices}, separators=(",", ":")) + ";\n")
    print(f"prices for {len(prices)} companies, as of {asof}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
