"""
Atlas 0.8.4: zones for Atlas Environment  ->  data/envzones/<theme>.js
    python3 pipeline/fetch_envzones.py   (downloads into pipeline/sources/raw/envzones/)
    python3 pipeline/build_envzones.py

Needs shapely and pyproj:  pip install shapely pyproj

Geometry is packed (see pack()): whole numbers of 1/10,000 degree, each point as the step from the last.
Each file calls window.ATLAS_ENVZ_LOADED(theme, data) when the page loads it (so it works over file:// too), and the
view loads a theme only when its tab is first opened. Shapes are simplified (floods to about 60 m, one shape per flood event; coast to about 30 m,
protected areas to about 50 m) and coordinates kept to 4 decimal places (about 10 m), which is enough at the zooms
the view uses; the original detail stays in the source files.

    floods.js        features: recorded floods (England and Wales): {y: year, m: month, s: source, ev: event id}
                     events:   one per flood event (the outlines recorded together): date, name, nation, outlines, hectares
    coast.js         features: erosion zones (England and Wales): {e: 2055 | 2105, d: metres (England) or a range (Wales)}
    heat.js          cells:    12 km squares, days above 30 °C a year at each step of STEPS (UKCP18 medians)
    conservation.js  features: National Parks and Ramsar wetlands: {k: "np" | "ramsar", n: name, y: year designated or null}
    fire.js          features: wildfire burnt areas seen by satellite (Scotland, 2026): {d: date, ha}
"""
import json, os, re
from collections import defaultdict
from shapely.geometry import shape, mapping, box
from shapely.ops import transform, unary_union
import warnings
warnings.filterwarnings("ignore", category=DeprecationWarning)
from pyproj import Transformer

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RAW = os.path.join(HERE, "sources", "raw", "envzones")
OUT = os.path.join(ROOT, "data", "envzones")
os.makedirs(OUT, exist_ok=True)


def load(name):
    return json.load(open(os.path.join(RAW, name), encoding="utf-8"))["features"]


def rnd(geom):
    """Round coordinates to 4 dp and drop the z value; drop rings that collapse."""
    def ring(r):
        out = []
        for p in r:
            q = [round(p[0], 4), round(p[1], 4)]
            if not out or out[-1] != q:
                out.append(q)
        return out if len(out) >= 4 else None
    g = mapping(geom)
    if g["type"] == "Polygon":
        rs = [x for x in (ring(r) for r in g["coordinates"]) if x]
        return {"type": "Polygon", "coordinates": rs} if rs else None
    if g["type"] == "MultiPolygon":
        ps = []
        for poly in g["coordinates"]:
            rs = [x for x in (ring(r) for r in poly) if x]
            if rs:
                ps.append(rs)
        return {"type": "MultiPolygon", "coordinates": ps} if ps else None
    return None


def simple(geojson_geom, tol):
    try:
        g = shape(geojson_geom)
        if not g.is_valid:
            g = g.buffer(0)
        g = g.simplify(tol, preserve_topology=True)
        return None if g.is_empty else g
    except Exception:
        return None


def feature(g, props):
    gg = rnd(g)
    return {"type": "Feature", "geometry": gg, "properties": props} if gg else None


def pack(ft):
    """Compact geometry: coordinates as whole numbers of 1/10,000 degree, each point stored as the step from the one
    before ([x0, y0, dx1, dy1, ...] per ring), polygons as lists of rings. The view's unpack() reverses it."""
    g = ft["geometry"]
    polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
    out = []
    for poly in polys:
        rings = []
        for r in poly:
            flat, px, py = [], 0, 0
            for x, y in r:
                ix, iy = round(x * 1e4), round(y * 1e4)
                flat += [ix - px, iy - py]; px, py = ix, iy
            rings.append(flat)
        out.append(rings)
    return [ft["properties"], out]


def write(theme, data, note):
    if "features" in data:
        data = dict(data, features=[pack(f) for f in data["features"]], packed=1)
    path = os.path.join(OUT, theme + ".js")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"/* Atlas 0.8.4: {note}. Generated by pipeline/build_envzones.py: don't edit by hand. */\n")
        fh.write(f"window.ATLAS_ENVZ_LOADED && ATLAS_ENVZ_LOADED({json.dumps(theme)}, " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ");\n")
    print(f"  {theme + '.js':<18} {os.path.getsize(path) / 1e6:6.1f} MB")


def year_month(s):
    m = re.match(r"(\d{4})-(\d{2})", str(s or ""))
    return (int(m.group(1)), int(m.group(2))) if m else (None, None)


def tidy(name):
    """Readable event names: "06MarchSpring1947" -> "March Spring 1947", "07301E900 FEB1953 Dartford" -> "Feb 1953 Dartford"."""
    n = name.replace("_", " ")
    n = re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Za-z])|(?<=[A-Z]{3})(?=[0-9])", " ", n)
    words = [w for w in n.split() if not re.fullmatch(r"\d{1,2}|\d+[A-Z]\d+|[A-Z]?\d{3,}[A-Z]?\d*|[A-Z]\d{3,}", w)]
    words = [w.capitalize() if w.isupper() and len(w) > 3 and w not in ("LNA",) else w for w in words]
    words = [w.capitalize() if w in ("JAN", "FEB", "MAR", "APR", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC") else w for w in words]
    return " ".join(words).strip(" -")


# ---------- floods (past): England and Wales ----------
SRC_EA = {"main river": "river", "ordinary watercourse": "river", "ephemeral watercourse": "river", "sea": "sea", "sewer": "surface",
          "drainage": "surface", "surface water": "surface", "groundwater": "ground"}
SRC_NRW = {"River": "river", "Small watercourse": "river", "Surface water": "surface", "Sea - still water": "sea", "Sea - wave overtopping": "sea", "Ground water": "ground"}
feats, events = [], {}
seen = set()
for f in load("ea_recorded_floods.geojson"):
    p = f["properties"]
    if p["rec_out_id"] in seen:
        continue
    seen.add(p["rec_out_id"])
    y, m = year_month(p.get("start_date"))
    if not y:
        continue
    src = SRC_EA.get(p.get("flood_src"), "sea" if p.get("tidal_f") == "True" or p.get("coastal_f") == "True" else "river" if p.get("fluvial_f") == "True" else "other")
    if src == "other" and p.get("flood_caus") == "groundwater/high water table":
        src = "ground"
    g = simple(f["geometry"], 0.0004)
    if not g:
        continue
    ev = "E" + str(p.get("rec_grp_id") or p["rec_out_id"])
    name = re.sub(r"_?(Aerial|Walked|Survey|Photo|Outline).*$", "", str(p.get("name") or ""), flags=re.I)
    name = tidy(re.sub(r"^\d{2}/\d{2}/\d{4}_?", "", name)) or "Recorded flood"
    e = events.setdefault(ev, {"id": ev, "d": p["start_date"][:10], "n": name, "nat": "E", "k": 0, "ha": 0.0, "s": src})
    e["k"] += 1
    ft = feature(g, {"y": y, "m": m, "s": src, "ev": ev})
    if ft:
        ft["_g"] = g; feats.append(ft)
for i, f in enumerate(load("nrw_historic_floods.geojson")):
    p = f["properties"]
    y, m = year_month(p.get("start_date"))
    if not y:
        continue
    g = simple(f["geometry"], 0.0004)
    if not g:
        continue
    ev = f"W{i}"
    src = SRC_NRW.get(p.get("flood_source"), "other")
    name = re.sub(r"\s*(walked|aerial|survey)?\s*outline\s*$", "", str(p.get("name") or ""), flags=re.I).strip() or "Recorded flood"
    events[ev] = {"id": ev, "d": str(p["start_date"])[:10], "n": name, "nat": "W", "k": 1, "ha": 0.0, "s": src}
    ft = feature(g, {"y": y, "m": m, "s": src, "ev": ev})
    if ft:
        ft["_g"] = g; feats.append(ft)
# one shape per event (an event's outlines often touch or overlap): far fewer, lighter features
grouped = defaultdict(list)
for ft in feats:
    grouped[ft["properties"]["ev"]].append(ft)
feats = []
for ev, fs in grouped.items():
    g = unary_union([f["_g"] for f in fs]).simplify(0.0006, preserve_topology=True)
    ft = feature(g, dict(fs[0]["properties"]))
    if ft:
        ft["_g"] = g; feats.append(ft)
# hectares in British National Grid (metres), so areas are right everywhere in Great Britain
to_bng = Transformer.from_crs(4326, 27700, always_xy=True).transform
for ft in feats:
    events[ft["properties"]["ev"]]["ha"] += transform(to_bng, ft.pop("_g")).area / 1e4
evlist = sorted(events.values(), key=lambda e: e["d"])
for e in evlist:
    e["ha"] = round(e["ha"], 1)
write("floods", {"features": feats, "events": evlist,
                 "src": "Environment Agency, Recorded Flood Outlines (England); Natural Resources Wales, Historic Flood Map (Wales). Open Government Licence v3.0."},
      f"recorded floods, England and Wales ({len(feats)} outlines, {len(evlist)} events)")

# ---------- coastal erosion (future): England and Wales ----------
coast = []
for e, name, field in ((2055, "NCERM_SMP_2055_70CC.geojson", "smp2055_70"), (2105, "NCERM_SMP_2105_70CC.geojson", "smp2105_70")):
    for f in json.load(open(os.path.join(RAW, "ncerm", name)))["features"]:
        p = f["properties"]
        g = simple(f["geometry"], 0.0003)
        d = p.get(field)
        if g and d is not None:
            ft = feature(g, {"e": e, "d": round(float(d)), "smp": p.get("smp_name"), "pol": p.get("mt_smp" if e == 2055 else "lt_smp")})
            if ft: coast.append(ft)
EPOCH = {"Medium": 2055, "Long": 2105}
for f in load("nrw_ncerm_all_smp.geojson"):
    p = f["properties"]
    e = next((v for k, v in EPOCH.items() if str(p.get("epoch", "")).startswith(k)), None)
    if not e:
        continue
    g = simple(f["geometry"], 0.0003)
    if g:
        ft = feature(g, {"e": e, "d": p.get("medium_smp" if e == 2055 else "long_smp"), "smp": p.get("smp_name"), "pol": None})
        if ft: coast.append(ft)
write("coast", {"features": coast,
                "src": "Environment Agency, National Coastal Erosion Risk Mapping 2024 (England: shoreline management plans delivered, higher central sea level rise); Natural Resources Wales, NCERM (Wales). Open Government Licence v3.0."},
      f"coastal erosion zones, England and Wales ({len(coast)})")

# ---------- heat: UK, 12 km grid ----------
STEPS = [["b81", "1981–2000", "HSD_baseline_81_00_median"], ["b01", "2001–2020", "HSD_baseline_01_20_median"],
         ["g15", "+1.5 °C", "HSD_15_median"], ["g20", "+2 °C", "HSD_20_median"], ["g25", "+2.5 °C", "HSD_25_median"],
         ["g30", "+3 °C", "HSD_30_median"], ["g40", "+4 °C", "HSD_40_median"]]
to_wgs = Transformer.from_crs(27700, 4326, always_xy=True).transform
cells = []
for f in load("metoffice_hot_days_12km.geojson"):
    p = f["properties"]
    x, y = p["Projection_x_coordinate"], p["Projection_y_coordinate"]
    sq = transform(to_wgs, box(x - 6000, y - 6000, x + 6000, y + 6000))
    vals = [p.get(s[2]) for s in STEPS]
    if all(v is None for v in vals):
        continue
    ft = feature(sq, {"v": [None if v is None else round(v, 1) for v in vals]})
    if ft: cells.append(ft)
write("heat", {"steps": [[a, b] for a, b, _ in STEPS], "features": cells,
               "src": "Met Office Climate Data Portal, Annual Count of Hot Summer Days - Projections (12km), from UKCP18 (RCP8.5, ensemble median). Open Government Licence v3.0."},
      f"hot summer days, UK 12 km grid ({len(cells)} cells)")

# ---------- conservation: National Parks and Ramsar wetlands ----------
cons = []
SCOT_NP = {"Loch Lomond and The Trossachs National Park": 2002, "Cairngorms National Park": 2003}   # Scottish Government designation orders
for f in load("ne_national_parks.geojson"):
    p = f["properties"]; g = simple(f["geometry"], 0.0005)
    y = int(1970 + p["DESIG_DATE"] / 1000 / 86400 / 365.2425) if p.get("DESIG_DATE") else None
    nm = p["NAME"].title().replace("And ", "and ")
    ft = g and feature(g, {"k": "np", "n": nm, "y": y, "nat": "E"})
    if ft: cons.append(ft)
for f in load("nrw_national_parks.geojson"):
    p = f["properties"]; g = simple(f["geometry"], 0.0005)
    ft = g and feature(g, {"k": "np", "n": p["np_name"].split(" / ")[-1], "y": int(str(p["desig_date"])[:4]), "nat": "W"})
    if ft: cons.append(ft)
for f in load("scot_national_parks.geojson"):
    p = f["properties"]; g = simple(f["geometry"], 0.0005)
    ft = g and feature(g, {"k": "np", "n": p["npname"].replace(" National Park", ""), "y": SCOT_NP.get(p["npname"]), "nat": "S"})
    if ft: cons.append(ft)
ramsar = defaultdict(list)
for name, nat, nk, ck, dk in (("ne_ramsar.geojson", "E", "NAME", "CODE", None), ("nrw_ramsar.geojson", "W", "RAM_name", "RAM_code", "DESIG_DATE"),
                              ("scot_ramsar.geojson", "S", "NAME", "EUROPEAN_CODE", None), ("ni_ramsar.geojson", "NI", "NAME", "REFERENCE", None)):
    for f in load(name):
        p = f["properties"]
        code = str(p.get(ck) or p.get(nk)).strip()
        g = simple(f["geometry"], 0.0005)
        if g:
            ramsar[(code, nat)].append((g, str(p.get(nk) or "").strip(), p.get(dk) if dk else None))
for (code, nat), parts in ramsar.items():   # one feature per site (some layers split a site into many parts)
    g = unary_union([x[0] for x in parts]).simplify(0.0005, preserve_topology=True)
    name = parts[0][1].replace(" RAMSAR SITE", "").replace(" Ramsar Site", "")
    name = name.title() if name.isupper() else name
    d = parts[0][2]
    ft = feature(g, {"k": "ramsar", "n": name, "y": int(str(d)[:4]) if d else None, "nat": nat, "code": code})
    if ft: cons.append(ft)
write("conservation", {"features": cons,
                       "src": "Natural England; Natural Resources Wales; Scottish Government and NatureScot; DAERA. Open Government Licence v3.0."},
      f"National Parks and Ramsar sites ({len(cons)})")

# ---------- wildfire: Scotland, 2026 (satellite) ----------
fire = []
for f in load("sepa_satellite_wildfire.geojson"):
    p = f["properties"]
    m = re.match(r"(\d{2})/(\d{2})/(\d{4})", str(p.get("src_date") or ""))
    g = simple(f["geometry"], 0.0002)
    if m and g:
        ft = feature(g, {"d": f"{m.group(3)}-{m.group(2)}-{m.group(1)}", "ha": round(p.get("area_ha") or 0, 1)})
        if ft: fire.append(ft)
write("fire", {"features": fire,
               "src": "SEPA, satellite observed extent (Copernicus Emergency Management Service, Sentinel-2). Open Government Licence v3.0."},
      f"wildfire burnt areas, Scotland 2026 ({len(fire)})")
