"""
Atlas 0.7.1: Westminster voting-intention polls -> data/polls.js   (python3 pipeline/build_polls.py)

sources/polls_wikipedia.csv   polls copied from Wikipedia's "Opinion polling for the next United Kingdom general election"
                              table (the pollsters' published figures; the table is CC BY-SA 4.0). Add new rows at the top
                              when you refresh it; the build keeps whatever is there.
The polling average is the plain mean of every poll whose fieldwork ended in the 21 days up to the latest poll, party by
party (a missing figure is left out of that party's mean). Atlas's seat projection (in app.js) applies the change from
the 2024 Great Britain result to every seat: uniform national swing. Standard library only.
"""
import csv, datetime, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PARTIES = ["lab", "con", "ref", "ld", "grn", "snp", "pc"]


def main():
    rows = list(csv.DictReader(open(os.path.join(HERE, "sources", "polls_wikipedia.csv"), encoding="utf-8")))
    rows.sort(key=lambda r: r["fieldwork_end"], reverse=True)
    latest = datetime.date.fromisoformat(rows[0]["fieldwork_end"])
    window = [r for r in rows if (latest - datetime.date.fromisoformat(r["fieldwork_end"])).days <= 21]
    avg = {}
    for p in PARTIES:
        vs = [float(r[p]) for r in window if r.get(p)]
        if vs:
            avg[p] = round(sum(vs) / len(vs), 1)
    out = {
        "source": "Wikipedia, 'Opinion polling for the next United Kingdom general election' (pollsters' published figures; table CC BY-SA 4.0)",
        "retrieved": "2026-10-28", "latest": rows[0]["fieldwork_end"], "window_days": 21, "n": len(window), "avg": avg,
        "polls": [[r["fieldwork_end"], r["pollster"], r["area"]] + [float(r[p]) if r.get(p) else None for p in PARTIES] for r in rows],
        "parties": PARTIES,
    }
    with open(os.path.join(ROOT, "data", "polls.js"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by pipeline/build_polls.py. Do not edit by hand.\nwindow.ATLAS_POLLS = ")
        json.dump(out, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    print("polls:", len(rows), "average of", len(window), "up to", rows[0]["fieldwork_end"], avg)


if __name__ == "__main__":
    main()
